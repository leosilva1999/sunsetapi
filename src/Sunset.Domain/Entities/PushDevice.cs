using Sunset.Domain.Enums;

namespace Sunset.Domain.Entities;

/// <summary>
/// A phone that may receive push notifications for one account. The Expo push token identifies the
/// installation of the app; it is personal data (a device identifier), so it is removed with the account
/// and when it goes unused. A token belongs to exactly one user at a time.
/// </summary>
public class PushDevice : BaseEntity
{
    public Guid UserId { get; private set; }

    /// <summary>"ExponentPushToken[...]". Unique across the table.</summary>
    public string Token { get; private set; } = null!;

    public PushPlatform Platform { get; private set; }

    /// <summary>Stable id of one installation of the app (generated by the app); lets a changed token replace the old row.</summary>
    public Guid? InstallId { get; private set; }

    public string? AppVersion { get; private set; }
    public string? Locale { get; private set; }

    /// <summary>Last time the app registered this device; drives the retention clean-up.</summary>
    public DateTime LastSeenAt { get; private set; }

    public User User { get; private set; } = null!;

    private PushDevice() { }

    public PushDevice(Guid userId, string token, PushPlatform platform, Guid? installId, string? appVersion, string? locale)
    {
        if (userId == Guid.Empty)
            throw new ArgumentException("UserId is required.", nameof(userId));

        UserId = userId;
        Refresh(token, platform, installId, appVersion, locale);
    }

    /// <summary>Applies a (re)registration: new token, platform and details, and marks the device as seen now.</summary>
    public void Refresh(string token, PushPlatform platform, Guid? installId, string? appVersion, string? locale)
    {
        if (string.IsNullOrWhiteSpace(token))
            throw new ArgumentException("Token is required.", nameof(token));

        Token = token;
        Platform = platform;
        InstallId = installId ?? InstallId;
        AppVersion = appVersion;
        Locale = locale;
        LastSeenAt = DateTime.UtcNow;
    }

    /// <summary>The same phone is now used by another account (shared device, logout without clean-up, account switch).</summary>
    public void MoveTo(Guid userId)
    {
        if (userId == Guid.Empty)
            throw new ArgumentException("UserId is required.", nameof(userId));

        UserId = userId;
    }
}
